CREATE TABLE IF NOT EXISTS Report(
    report_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id BIGINT NOT NULL,
    report_reason VARCHAR(250) NOT NULL,
    category_id BIGINT NOT NULL,
    target_type report_target_type NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    report_status report_status NOT NULL DEFAULT 'OPEN',
    resolved_at TIMESTAMPTZ,

    discussion_id BIGINT,
    problem_id BIGINT,
    wall_section_id BIGINT,
    user_id BIGINT,

    CONSTRAINT fk_reporter_id
        FOREIGN KEY (reporter_id) REFERENCES user_account(user_id),
    CONSTRAINT fk_report_category
        FOREIGN KEY (category_id) REFERENCES Report_Category(category_id),
    CONSTRAINT fk_report_discussion
        FOREIGN KEY (discussion_id) REFERENCES Discussion_Root(discussion_id),
    CONSTRAINT fk_report_problem
        FOREIGN KEY (problem_id) REFERENCES Climbing_Problem(problem_id),
    CONSTRAINT fk_report_wall_section
        FOREIGN KEY (wall_section_id) REFERENCES Wall_Section(wall_section_id),
    CONSTRAINT fk_report_user
        FOREIGN KEY (user_id) REFERENCES User_Account(user_id),

    CONSTRAINT chk_one_report_target CHECK(
        (target_type = 'DISCUSSION' AND discussion_id IS NOT NULL AND problem_id IS NULL
            AND wall_section_id is NULL AND user_id IS NULL)
            OR
        (target_type = 'WALL_SECTION' AND wall_section_id IS NOT NULL AND discussion_id IS NULL
            AND problem_id IS NULL AND user_id IS NULL)
            OR
        (target_type = 'CLIMBING_PROBLEM' AND problem_id IS NOT NULL AND discussion_id IS NULL
            AND wall_section_id IS NULL AND user_id IS NULL)
            OR
        (target_type = 'USER_ACCOUNT' AND user_id IS NOT NULL AND discussion_id IS NULL
            AND wall_section_id IS NULL AND problem_id IS NULL)
        )
);

CREATE UNIQUE INDEX uq_one_open_report_per_user_target
    ON Report(
        reporter_id,
        target_type,
        COALESCE(discussion_id, 0),
        COALESCE(problem_id, 0),
        COALESCE(wall_section_id, 0),
        COALESCE(user_id, 0)
        )
    WHERE report_status = 'OPEN';

CREATE TYPE appeal_status AS Enum(
    'OPEN',
    'APPROVED',
    'DENIED'
    );

CREATE TABLE IF NOT EXISTS Appeal(
    appeal_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id BIGINT NOT NULL UNIQUE,
    appeal_user_id BIGINT NOT NULL,
    reason VARCHAR(250) NOT NULL,
    status appeal_status NOT NULL DEFAULT 'OPEN',
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMPTZ,
    reviewed_by BIGINT,
    admin_note VARCHAR(255),

    CONSTRAINT fk_report
        FOREIGN KEY (report_id) REFERENCES report(report_id),
    CONSTRAINT fk_appeal_user
        FOREIGN KEY (appeal_user_id) REFERENCES user_account(user_id),
    CONSTRAINT fk_appeal_reviewer
        FOREIGN KEY (reviewed_by) REFERENCES User_Account(user_id)
);

CREATE TABLE IF NOT EXISTS Moderation_Action (
    action_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id BIGINT NOT NULL,
    admin_user_id BIGINT NOT NULL,
    action_type moderate_action_type NOT NULL,
    admin_notes VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_moderate_report
        FOREIGN KEY (report_id) REFERENCES Report(report_id),
    CONSTRAINT fk_moderate_admin
        FOREIGN KEY (admin_user_id) REFERENCES User_Account(user_id)
);

CREATE TABLE IF NOT EXISTS Event_Type(
    event_type_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type_name VARCHAR(50) NOT NULL UNIQUE,
    description VARCHAR(100)
);


CREATE TYPE event_target_type AS ENUM(
    'REPORT',
    'DISCUSSION',
    'CLIMBING_PROBLEM',
    'WALL_SECTION',
    'USER_ACCOUNT'
    );

CREATE TABLE IF NOT EXISTS Events(
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type_id BIGINT NOT NULL,
    actor_user_id BIGINT,
    target_type event_target_type NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    report_id BIGINT,
    discussion_id BIGINT,
    problem_id BIGINT,
    wall_section_id BIGINT,
    user_id BIGINT,


    CONSTRAINT fk_event_type
        FOREIGN KEY (event_type_id) REFERENCES event_type (event_type_id),
    CONSTRAINT fk_actor_id
        FOREIGN KEY (actor_user_id) REFERENCES User_Account(user_id),
    CONSTRAINT fk_event_report
        FOREIGN KEY (report_id) REFERENCES Report(report_id),
    CONSTRAINT fk_event_discussion
        FOREIGN KEY (discussion_id) REFERENCES Discussion_Root(discussion_id),
    CONSTRAINT fk_event_problem
        FOREIGN KEY (problem_id) REFERENCES Climbing_Problem(problem_id),
    CONSTRAINT fk_event_wall_section
        FOREIGN KEY (wall_section_id) REFERENCES Wall_Section(wall_section_id),
    CONSTRAINT fk_event_user
        FOREIGN KEY (user_id) REFERENCES User_Account(user_id),

    CONSTRAINT chk_one_event_target CHECK(
        (target_type = 'REPORT' AND report_id IS NOT NULL AND problem_id IS NULL
            AND discussion_id IS NULL AND wall_section_id IS NULL AND user_id IS NULL)
            OR
        (target_type = 'DISCUSSION' AND discussion_id IS NOT NULL AND problem_id IS NULL
            AND wall_section_id is NULL AND user_id IS NULL AND report_id IS NULL)
            OR
        (target_type = 'WALL_SECTION' AND wall_section_id IS NOT NULL AND discussion_id IS NULL
            AND problem_id IS NULL AND user_id IS NULL AND report_id IS NULL)
            OR
        (target_type = 'CLIMBING_PROBLEM' AND problem_id IS NOT NULL AND discussion_id IS NULL
            AND wall_section_id IS NULL AND user_id IS NULL AND report_id IS NULL)
            OR
        (target_type = 'USER_ACCOUNT' AND user_id IS NOT NULL AND discussion_id IS NULL
            AND wall_section_id IS NULL AND problem_id IS NULL AND report_id IS NULL)
        )
);

CREATE TABLE IF NOT EXISTS Notification(
    notification_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL,
    recipient_user_id BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    read_at TIMESTAMPTZ,

    CONSTRAINT fk_event_id
        FOREIGN KEY (event_id) REFERENCES events (event_id),
    CONSTRAINT fk_recipient_user
        FOREIGN KEY (recipient_user_id) REFERENCES user_account(user_id),

    UNIQUE(event_id, recipient_user_id)
);

CREATE INDEX idx_report_queue ON Report (report_status, created_at);
CREATE INDEX idx_notification_recipient ON Notification (recipient_user_id, created_at DESC);


