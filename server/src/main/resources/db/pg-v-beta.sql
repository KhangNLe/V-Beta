CREATE TABLE IF NOT EXISTS Gym_Role (
    role_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_type VARCHAR(25) NOT NULL
);

CREATE TABLE IF NOT EXISTS Gym_Action(
    action_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    action_definition varchar(50)
);

CREATE TABLE IF NOT EXISTS Role_Permission(
    role_id BIGINT NOT NULL,
    action_id BIGINT NOT NULL,
    PRIMARY KEY (role_id, action_id),
    FOREIGN KEY (role_id) REFERENCES Gym_Role (role_id),
    FOREIGN KEY (action_id) REFERENCES Gym_Action (action_id)
);

CREATE TABLE IF NOT EXISTS User_Account(
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(25) NOT NULL,
    email VARCHAR(225) NOT NULL,
    firebase_uid VARCHAR(128) NOT NULL UNIQUE,
    gym_role_id BIGINT,
    FOREIGN KEY (gym_role_id) REFERENCES Gym_Role (role_id)
);


CREATE TABLE IF NOT EXISTS Climbing_Grade(
    grade_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grade VARCHAR(10) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS Wall_Section(
    wall_section_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    info VARCHAR(250),
    wall_section_name VARCHAR(30) NOT NULL
);

CREATE TABLE IF NOT EXISTS Climbing_Problem(
    problem_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    hold_color VARCHAR(25) NOT NULL,
    info VARCHAR(250),
    lifecycle_status VARCHAR(25),
    create_date TIMESTAMP,
    wall_section_id BIGINT,
    assigned_grade_id BIGINT,
    FOREIGN KEY (wall_section_id) REFERENCES Wall_Section (wall_section_id),
    FOREIGN KEY (assigned_grade_id) REFERENCES Climbing_Grade (grade_id)
);


CREATE TYPE discussion_kind AS ENUM('COMMENT', 'BETA');

CREATE TABLE IF NOT EXISTS Discussion_Root(
    discussion_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_discussion_id BIGINT,
    problem_id BIGINT NOT NULL,
    user_id BIGINT NOT NULL,
    discussion_type discussion_kind NOT NULL,
    create_at TIMESTAMP,
    deleted_by BIGINT,
    deleted_reason VARCHAR(100),
    deleted_at TIMESTAMP,

    CONSTRAINT fk_discussion_parent
        FOREIGN KEY (parent_discussion_id) REFERENCES Discussion_Root (discussion_id),
    CONSTRAINT fk_discussion_problem
        FOREIGN KEY (problem_id) REFERENCES Climbing_Problem (problem_id),
    CONSTRAINT fk_discussion_user
        FOREIGN KEY (user_id) REFERENCES User_Account (user_id),
    CONSTRAINT fk_discussion_deleted_by
        FOREIGN KEY (deleted_by) REFERENCES User_Account (user_id),

    CONSTRAINT chk_not_self_parent
        CHECK (parent_discussion_id IS NULL OR parent_discussion_id <> discussion_id)
);

CREATE INDEX IF NOT EXISTS idx_discussion_root_problem_created_id
    ON Discussion_Root (problem_id, create_at ASC, discussion_id ASC);

CREATE INDEX IF NOT EXISTS idx_discussion_root_parent_created_id
    ON Discussion_Root (parent_discussion_id, create_at DESC, discussion_id DESC);

CREATE INDEX IF NOT EXISTS idx_discussion_root_problem_parent_created_id
    ON Discussion_Root (problem_id, parent_discussion_id, create_at DESC, discussion_id DESC);

CREATE TABLE IF NOT EXISTS User_Perceive_Grade(
    user_id BIGINT NOT NULL,
    grade_id BIGINT NOT NULL,
    problem_id BIGINT NOT NULL,
    PRIMARY KEY (user_id, problem_id),
    FOREIGN KEY (user_id) REFERENCES User_Account (user_id),
    FOREIGN KEY (problem_id) REFERENCES Climbing_Problem (problem_id),
    FOREIGN KEY (grade_id) REFERENCES Climbing_Grade (grade_id)
);

CREATE TABLE IF NOT EXISTS Solution_Beta(
    beta_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    discussion_id BIGINT UNIQUE NOT NULL,
    beta_name VARCHAR(250) NOT NULL,
    video_url VARCHAR(250) NOT NULL UNIQUE,
    create_date TIMESTAMP,

    CONSTRAINT fk_discussion_root
        FOREIGN KEY (discussion_id) REFERENCES Discussion_Root(discussion_id)
);

CREATE TABLE IF NOT EXISTS Discussion_Comment(
    comment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    discussion_id BIGINT UNIQUE NOT NULL,
    info VARCHAR(250),
    create_date TIMESTAMP,

    CONSTRAINT fk_discussion_root
        FOREIGN KEY (discussion_id) REFERENCES Discussion_Root (discussion_id)
);

CREATE TYPE report_status AS Enum(
    'OPEN',
    'DISMISSED',
    'CONTENT_REMOVED',
    'APPEAL_PENDING',
    'CONTENT_RESTORED',
    'APPEAL_DENIED'
    );

CREATE TABLE IF NOT EXISTS Report_Category(
    category_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name VARCHAR(40) NOT NULL UNIQUE,
    weight INTEGER NOT NULL UNIQUE CHECK (weight > 0)
);

